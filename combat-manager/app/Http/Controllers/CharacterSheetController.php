<?php

namespace App\Http\Controllers;

use App\Models\Character;
use Illuminate\Support\Facades\Gate;
use Illuminate\View\View;

class CharacterSheetController extends Controller
{
    public function show(
        Character $character
    ): View {
        /*
        |--------------------------------------------------------------------------
        | Autorização
        |--------------------------------------------------------------------------
        |
        | Pode abrir a ficha:
        |
        | - o próprio dono;
        | - o Mestre de uma campanha na qual essa ficha foi
        |   explicitamente compartilhada.
        |
        */

        Gate::authorize(
            'view',
            $character
        );

        $character->load([
            /*
            |--------------------------------------------------------------------------
            | Identidade / Progressão
            |--------------------------------------------------------------------------
            */

            'classes',

            /*
            |--------------------------------------------------------------------------
            | Atributos
            |--------------------------------------------------------------------------
            */

            'abilities',

            /*
            |--------------------------------------------------------------------------
            | Perícias
            |--------------------------------------------------------------------------
            */

            'skills',

            /*
            |--------------------------------------------------------------------------
            | Salvaguardas
            |--------------------------------------------------------------------------
            */

            'savingThrows',

            /*
            |--------------------------------------------------------------------------
            | Características
            |--------------------------------------------------------------------------
            */

            'features',

            /*
            |--------------------------------------------------------------------------
            | Recursos
            |--------------------------------------------------------------------------
            */

            'resources',

            /*
            |--------------------------------------------------------------------------
            | Combate
            |--------------------------------------------------------------------------
            */

            'combat.concentrationSpell',

            /*
            |--------------------------------------------------------------------------
            | Conjuração
            |--------------------------------------------------------------------------
            */

            'spellcasting',

            /*
            |--------------------------------------------------------------------------
            | Magias
            |--------------------------------------------------------------------------
            */

            'characterSpells.spell',

            /*
            |--------------------------------------------------------------------------
            | Spell Slots
            |--------------------------------------------------------------------------
            */

            'spellSlots',

            /*
            |--------------------------------------------------------------------------
            | Inventário
            |--------------------------------------------------------------------------
            */

            'items',
        ]);

        return view('characters.show', [
            'character' => $character,
        ]);
    }
}